    static func key(_ key: Key) -> LocalizedStringKey {
        LocalizedStringKey(key.rawValue)
    }

    static func string(_ key: Key, _ arguments: CVarArg...) -> String {
        let locale = preferredLocale()
        let bundle = Bundle(
            path: Bundle.main.path(forResource: locale.identifier, ofType: "lproj") ?? "",
        ) ?? .main
        let format = NSLocalizedString(key.rawValue, bundle: bundle, value: key.rawValue, comment: "")
        guard !arguments.isEmpty else { return format }
        return String(format: format, locale: locale, arguments: arguments)
    }

    /// Format strings must follow the in-app language immediately, even though SwiftUI's
    /// `LocalizedStringKey` is resolved from the environment. Reading the shared preference
    /// here keeps interpolated labels in sync without changing the process-wide system locale.
    private static func preferredLocale() -> Locale {
        switch UserDefaults.standard.string(forKey: "anime.settings.language") {
        case "SimplifiedChinese": return Locale(identifier: "zh-Hans")
        case "TraditionalChinese": return Locale(identifier: "zh-Hant")
        case "English": return Locale(identifier: "en")
        case "Japanese": return Locale(identifier: "ja")
        default:
            let identifier = Locale.preferredLanguages.first?.lowercased() ?? "zh-hans"
            if identifier.hasPrefix("ja") { return Locale(identifier: "ja") }
            if identifier.hasPrefix("en") { return Locale(identifier: "en") }
            if identifier.contains("hant") || identifier.contains("tw") || identifier.contains("hk") || identifier.contains("mo") {
                return Locale(identifier: "zh-Hant")
            }
            return Locale(identifier: "zh-Hans")
        }
    }
